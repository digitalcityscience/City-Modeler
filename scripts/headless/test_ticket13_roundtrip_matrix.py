"""Ticket 13: round-trip matrix across both schema versions.

Runs the 15-row matrix from docs/agent/semantic-hierarchy/issues/
13-roundtrip-matrix-and-flag-default.md against real fixtures, for both
CityGML 2 and CityGML 3, with ``use_semantic_objects`` on. For each row this
records: input count, imported object count, parent hierarchy, exported
feature count, geometry comparison, gml:id preservation, and (via a
companion xmllint pass outside this script) schema validation.

Row 15 (legacy single-mesh, flag OFF, byte-identical to pre-ticket-06
output) is deliberately NOT covered here - it needs a second Blender
process running the pre-ticket-06 code for comparison and lives in
test_ticket13_legacy_byte_identical.py instead.

Usage:
    SP=/tmp/cgml-probe-11
    BLENDER_USER_SCRIPTS=$SP/bscripts blender --background --factory-startup \\
      --python scripts/headless/test_ticket13_roundtrip_matrix.py -- \\
      /tmp/cgml-out-13
"""
import json
import os
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "pydeps"))

import bpy

ADDON = "city_modeler"
REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURES_DIR = REPO_ROOT / "test_files"

RAILWAY_V2 = FIXTURES_DIR / "Building" / "Railway_Scene_LoD3_CityGML2_Building_only.gml"
RAILWAY_V3 = FIXTURES_DIR / "Building" / "Railway_Scene_LoD3_CityGML3_Building_only.gml"
INSTALL_V2 = FIXTURES_DIR / "Building" / "SemanticHierarchy_Installations_LoD3_CityGML2.gml"
INSTALL_V3 = FIXTURES_DIR / "Building" / "SemanticHierarchy_Installations_LoD3_CityGML3.gml"
APPEAR_V2 = FIXTURES_DIR / "Building" / "SemanticHierarchy_Appearance_LoD3_CityGML2.gml"
APPEAR_V3 = FIXTURES_DIR / "Building" / "SemanticHierarchy_Appearance_LoD3_CityGML3.gml"
PARTS_V2 = FIXTURES_DIR / "BuildingParts" / "BuildingParts_citygml2.gml"
PARTS_V3 = FIXTURES_DIR / "BuildingParts" / "BuildingParts_citygml3.gml"

RESULTS = {"2.0": {}, "3.0": {}}
FAILURES = []


def args():
    return sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []


def _local_name(tag):
    if isinstance(tag, str) and tag.startswith("{") and "}" in tag:
        return tag.rsplit("}", 1)[1]
    return tag


def counts(path):
    root = ET.parse(path).getroot()
    c = {}
    for elem in root.iter():
        local = _local_name(str(elem.tag))
        c[local] = c.get(local, 0) + 1
    return c


# Geometry-container ids (Polygon/LinearRing/MultiSurface) are legitimately
# regenerated by export - tickets 07/11 reconstruct exported geometry from
# each object's own mesh ("material-driven mesh" reconstruction), not by
# echoing the source XML's geometry elements verbatim. gml:id preservation
# for the matrix means FEATURE identity survives (Building/WallSurface/
# Window/Door/BuildingInstallation/BuildingPart), which is what
# surface_id_map and the round-trip contracts in README S3 actually promise.
_GEOMETRY_CONTAINER_TAGS = {"Polygon", "LinearRing", "MultiSurface", "Solid", "CompositeSurface"}


def gml_ids(path, feature_level_only=False):
    root = ET.parse(path).getroot()
    ids = set()
    for elem in root.iter():
        gid = elem.get("{http://www.opengis.net/gml/3.2}id") or elem.get("{http://www.opengis.net/gml}id")
        if not gid:
            continue
        if feature_level_only and _local_name(str(elem.tag)) in _GEOMETRY_CONTAINER_TAGS:
            continue
        ids.add(gid)
    return ids


def fresh_import(gml, version, import_appearance=True):
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.preferences.addon_enable(module=ADDON)
    bpy.context.scene.cgml3.use_semantic_objects = True
    res = bpy.ops.cgml3.import_gml_file(filepath=str(gml), import_appearance=import_appearance)
    assert res == {'FINISHED'}, f"import failed for {gml}: {res}"


def export(path, version):
    res = bpy.ops.cgml3.export_gml_file(filepath=str(path), citygml_version=version)
    assert res == {'FINISHED'}, f"export failed for {path}: {res}"


def objects_by_feature():
    by_feature = {}
    for o in bpy.data.objects:
        feat = o.get("cgml3_feature")
        by_feature.setdefault(feat, []).append(o)
    return by_feature


def record(version, row, ok, detail):
    RESULTS[version][row] = {"ok": ok, "detail": detail}
    status = "OK" if ok else "FAIL"
    print(f"[ticket13][{version}][{row}] {status}: {detail}")
    if not ok:
        FAILURES.append(f"{version}/{row}: {detail}")


def check(version, row, condition, detail):
    record(version, row, bool(condition), detail)


# ---------------------------------------------------------------------------
# Rows 1-5, 9, 12: structural counts + hierarchy from the Railway fixture.
# ---------------------------------------------------------------------------

def run_railway(version, gml, out_dir):
    fresh_import(gml, version)
    by_feature = objects_by_feature()

    wall_key = "WallSurface"
    win_key = "WindowSurface" if version == "3.0" else "Window"
    door_key = "DoorSurface" if version == "3.0" else "Door"

    walls = by_feature.get(wall_key, [])
    windows = by_feature.get(win_key, [])
    doors = by_feature.get(door_key, [])

    input_counts = counts(gml)
    input_win_key = "WindowSurface" if version == "3.0" else "Window"
    input_door_key = "DoorSurface" if version == "3.0" else "Door"

    # Row 1: WallSurface
    check(version, "01_wall_surface",
          len(walls) == 9 == input_counts.get(wall_key, 0),
          f"input={input_counts.get(wall_key, 0)} imported={len(walls)} expected=9")

    # Row 2: Window
    check(version, "02_window",
          len(windows) == 15 == input_counts.get(input_win_key, 0),
          f"input={input_counts.get(input_win_key, 0)} imported={len(windows)} expected=15")

    # Row 3: Door
    check(version, "03_door",
          len(doors) == 6 == input_counts.get(input_door_key, 0),
          f"input={input_counts.get(input_door_key, 0)} imported={len(doors)} expected=6")

    # Row 4: a WallSurface with multiple Window children.
    children_by_wall = {}
    for opening in windows + doors:
        parent = opening.parent
        if parent is not None:
            children_by_wall.setdefault(parent.name, []).append(opening)
    multi_window_walls = [
        w for w, kids in children_by_wall.items()
        if sum(1 for k in kids if k.get("cgml3_feature") == win_key) >= 2
    ]
    check(version, "04_wall_multi_window",
          len(multi_window_walls) >= 1,
          f"walls with >=2 windows: {len(multi_window_walls)} ({multi_window_walls[:2]})")

    # Row 5: a WallSurface with both a Window and a Door child.
    mixed_walls = [
        w for w, kids in children_by_wall.items()
        if any(k.get("cgml3_feature") == win_key for k in kids)
        and any(k.get("cgml3_feature") == door_key for k in kids)
    ]
    check(version, "05_wall_window_and_door",
          len(mixed_walls) >= 1,
          f"walls with window+door: {len(mixed_walls)} ({mixed_walls[:2]})")

    # Row 7: BuildingInstallation named "Chimney N" with bldg:function 1030 - the
    # SIG3D BuildingInstallation_function code for a chimney (OGC 12-019 Annex C.3).
    # B44: that code list is the one the add-on reads and writes, so these resolve
    # to Chimney by their function code (gml:name is still never an input).
    installations = by_feature.get("BuildingInstallation", [])
    chimneys = [o for o in installations if o.get("cgml_semantic_type") == "Chimney"]
    check(version, "07_chimney_as_installation",
          len(chimneys) == 2 and all(c.get("cgml_subtype_origin") == "function" for c in chimneys),
          f"chimneys={len(chimneys)} origins={[c.get('cgml_subtype_origin') for c in chimneys]}")

    # Row 12: opening interior ring - the fixture carries real interior
    # rings (wall cutouts + window frame reveals), and export below does not
    # trip the ticket-09 desync guard on this untouched fixture (paired
    # ring/opening geometry matches by construction - see ticket 09's
    # dedicated suite for the exhaustive per-pair proof).
    check(version, "12_opening_interior_ring",
          input_counts.get("interior", 0) > 0,
          f"input interior rings={input_counts.get('interior', 0)} (pairing verified by ticket 09's dedicated suite)")

    # Parent hierarchy: every opening parents to a WallSurface; Chimneys
    # parent directly to the Building.
    all_openings_parented = all(o.parent is not None and o.parent.get("cgml3_feature") == wall_key
                                 for o in windows + doors)
    building_obj = next((o for o in bpy.data.objects if o.get("cgml3_feature") == "Building"), None)
    chimneys_parent_to_building = all(c.parent is building_obj for c in chimneys) if building_obj else False
    check(version, "hierarchy_parenting",
          all_openings_parented and chimneys_parent_to_building,
          f"openings_parented={all_openings_parented} chimneys_to_building={chimneys_parent_to_building}")

    orig_ids = gml_ids(gml, feature_level_only=True)

    export_path = out_dir / f"railway_{version.replace('.', '_')}_export.gml"
    export(export_path, version)
    export_counts = counts(export_path)
    exported_ids = gml_ids(export_path, feature_level_only=True)

    # window-door-upload ticket 02: CityGML 3 non-streaming import turns this
    # fixture's one genuinely flat (single-polygon) Door into a 4 cm solid
    # prism: its one quad becomes a closed box of 6 quads, so the export has
    # 5 gml:Polygon elements more than the input (6 counted a zero-length side
    # face from a duplicated closing vertex, removed by 08028eb). The builder
    # gives CityGML 2 openings no depth, so its Polygon count must still match
    # the input exactly.
    # the 3.0 Door's synthetic display prism is exported flat again
    # (facade_placement.flat_synthetic_openings): every version matches the input
    expected_polygon_count = input_counts.get("Polygon")
    check(version, "export_counts_match_input",
          export_counts.get(wall_key) == 9
          and export_counts.get(win_key if version == "3.0" else "Window") == 15
          and export_counts.get(door_key if version == "3.0" else "Door") == 6
          and export_counts.get("Polygon") == expected_polygon_count,
          f"export_counts={ {k: export_counts.get(k) for k in (wall_key, win_key, door_key, 'Polygon')} } "
          f"expected_polygon={expected_polygon_count}")

    check(version, "gml_id_preservation",
          orig_ids.issubset(exported_ids),
          f"missing_ids={len(orig_ids - exported_ids)} of {len(orig_ids)}")

    # Round-trip: re-import the export, counts must match the fixture again.
    fresh_import(export_path, version)
    reimport_by_feature = objects_by_feature()
    reimport_ok = (
        len(reimport_by_feature.get(wall_key, [])) == 9
        and len(reimport_by_feature.get(win_key, [])) == 15
        and len(reimport_by_feature.get(door_key, [])) == 6
    )
    check(version, "roundtrip_reimport_counts",
          reimport_ok,
          f"reimport wall={len(reimport_by_feature.get(wall_key, []))} "
          f"window={len(reimport_by_feature.get(win_key, []))} door={len(reimport_by_feature.get(door_key, []))}")


# ---------------------------------------------------------------------------
# Rows 6, 8, 9: Balcony/Chimney subtype resolution from the ticket-03
# installations fixture (class rung, function rung, name rung).
# ---------------------------------------------------------------------------

def run_installations(version, gml, out_dir):
    fresh_import(gml, version)
    by_feature = objects_by_feature()
    installations = by_feature.get("BuildingInstallation", [])

    def find(suffix):
        for o in installations:
            gml_id = o.get("gml_id") or ""
            if suffix in gml_id:
                return o
        return None

    class_balcony = find("CLASS_BALCONY")
    function_chimney = find("FUNCTION_CHIMNEY")
    name_balcony = find("NAME_BALCONY")
    bare = find("BARE")
    conflict = find("CONFLICT")

    check(version, "08_balcony_class_function",
          class_balcony is not None
          and class_balcony.get("cgml_semantic_type") == "Balcony"
          and class_balcony.get("cgml_subtype_origin") == "class",
          f"class_balcony type={class_balcony.get('cgml_semantic_type') if class_balcony else None} "
          f"origin={class_balcony.get('cgml_subtype_origin') if class_balcony else None}")

    check(version, "09_chimney_class_function",
          function_chimney is not None
          and function_chimney.get("cgml_semantic_type") == "Chimney"
          and function_chimney.get("cgml_subtype_origin") == "function",
          f"function_chimney type={function_chimney.get('cgml_semantic_type') if function_chimney else None} "
          f"origin={function_chimney.get('cgml_subtype_origin') if function_chimney else None}")

    # A gml:name of "Balcony 1" with no class/function/usage. Under the
    # strict subtype policy (appearance ticket 01) gml:name is never a
    # classification input, so this stays generic BuildingInstallation
    # rather than resolving to Balcony.
    check(version, "06_balcony_as_installation",
          name_balcony is not None
          and name_balcony.get("cgml_semantic_type") == "BuildingInstallation"
          and name_balcony.get("cgml_subtype_origin") == "generic",
          f"name_balcony type={name_balcony.get('cgml_semantic_type') if name_balcony else None} "
          f"origin={name_balcony.get('cgml_subtype_origin') if name_balcony else None}")

    check(version, "resolver_bare_and_conflict",
          bare is not None and bare.get("cgml_semantic_type") in (None, "BuildingInstallation")
          and conflict is not None and conflict.get("cgml_semantic_type") == "Chimney",
          f"bare_type={bare.get('cgml_semantic_type') if bare else None} "
          f"conflict_type={conflict.get('cgml_semantic_type') if conflict else None}")

    orig_ids = gml_ids(gml, feature_level_only=True)
    export_path = out_dir / f"installations_{version.replace('.', '_')}_export.gml"
    export(export_path, version)
    exported_ids = gml_ids(export_path, feature_level_only=True)
    check(version, "installations_gml_id_preservation",
          orig_ids.issubset(exported_ids),
          f"missing_ids={len(orig_ids - exported_ids)} of {len(orig_ids)}")

    # Verbatim-provenance guard: no fabricated class/function should appear
    # for the bare/name-only installations (README decision 3).
    export_text = export_path.read_text(encoding="utf-8")
    check(version, "no_fabricated_semantics",
          "5010" not in export_text.split("SEMHIER_INST_BARE")[-1][:400]
          if "SEMHIER_INST_BARE" in export_text else True,
          "bare installation's export region inspected for fabricated class codes")


# ---------------------------------------------------------------------------
# Rows 10, 11: source appearance on a Window and on a Balcony-class
# BuildingInstallation survives the explode + export.
# ---------------------------------------------------------------------------

def run_appearance(version, gml, out_dir):
    fresh_import(gml, version, import_appearance=True)
    by_feature = objects_by_feature()
    win_key = "WindowSurface" if version == "3.0" else "Window"
    windows = by_feature.get(win_key, [])
    installations = by_feature.get("BuildingInstallation", [])
    balcony = next((o for o in installations if o.get("cgml_semantic_type") == "Balcony"), None)

    def has_source_color(obj, expect_rgb, tol=0.05):
        for slot in obj.material_slots:
            mat = slot.material
            if not mat:
                continue
            if mat.use_nodes and mat.node_tree:
                bsdf = next((n for n in mat.node_tree.nodes if n.type == "BSDF_PRINCIPLED"), None)
                if bsdf is not None:
                    col = bsdf.inputs["Base Color"].default_value
                    rgb = (col[0], col[1], col[2])
                else:
                    continue
            else:
                rgb = tuple(mat.diffuse_color[:3])
            if all(abs(rgb[i] - expect_rgb[i]) < tol for i in range(3)):
                return True
        return False

    # window-door-upload ticket 02: a flat CityGML 3 Window now unconditionally
    # gets the amber authored-glass colour instead of showing its own source
    # X3DMaterial - overriding this fixture's blue (0.1, 0.2, 0.8) is the
    # ticket's own explicit, intended behavior. CityGML 2 isn't wired up yet
    # (ticket 03), so its Window still shows its real source colour.
    window_expect_rgb = (0.85, 0.55, 0.20) if version == "3.0" else (0.1, 0.2, 0.8)
    window_has_color = len(windows) >= 1 and has_source_color(windows[0], window_expect_rgb)
    check(version, "10_window_source_appearance",
          window_has_color,
          f"window_count={len(windows)} source_color_matched={window_has_color} expect_rgb={window_expect_rgb}")

    balcony_has_color = balcony is not None and has_source_color(balcony, (0.8, 0.6, 0.1))
    check(version, "11_balcony_source_appearance",
          balcony_has_color,
          f"balcony_found={balcony is not None} source_color_matched={balcony_has_color}")

    export_path = out_dir / f"appearance_{version.replace('.', '_')}_export.gml"
    export(export_path, version)
    export_counts = counts(export_path)
    check(version, "appearance_export_has_x3dmaterial",
          export_counts.get("X3DMaterial", 0) >= 2,
          f"X3DMaterial count in export={export_counts.get('X3DMaterial', 0)}")


# ---------------------------------------------------------------------------
# Row 13: WallSurface under BuildingPart.
# ---------------------------------------------------------------------------

def run_building_parts(version, gml, out_dir):
    fresh_import(gml, version)
    by_feature = objects_by_feature()
    walls = by_feature.get("WallSurface", [])
    parts = by_feature.get("BuildingPart", [])
    building = next((o for o in bpy.data.objects if o.get("cgml3_feature") == "Building"), None)

    check(version, "13_wallsurface_input_count",
          len(walls) == 2,
          f"WallSurface objects={len(walls)} (expected 2: one under Building, one under BuildingPart)")

    part_wall = next((w for w in walls if w.parent is not None and w.parent.get("cgml3_feature") == "BuildingPart"), None)
    building_wall = next((w for w in walls if w.parent is building), None)

    check(version, "13_wallsurface_under_buildingpart",
          len(parts) == 1 and part_wall is not None and building_wall is not None,
          f"parts={len(parts)} part_wall_found={part_wall is not None} building_wall_found={building_wall is not None}")

    orig_ids = gml_ids(gml, feature_level_only=True)
    export_path = out_dir / f"buildingparts_{version.replace('.', '_')}_export.gml"
    export(export_path, version)
    exported_ids = gml_ids(export_path, feature_level_only=True)
    export_counts = counts(export_path)
    check(version, "13_export_preserves_hierarchy",
          orig_ids.issubset(exported_ids) and export_counts.get("WallSurface") == 2
          and export_counts.get("BuildingPart") == 1,
          f"missing_ids={len(orig_ids - exported_ids)} export_wall={export_counts.get('WallSurface')} "
          f"export_part={export_counts.get('BuildingPart')}")


# ---------------------------------------------------------------------------
# Row 14: export after editing child geometry (Window vertices moved).
# ---------------------------------------------------------------------------

def run_edit_geometry(version, gml, out_dir):
    win_key = "WindowSurface" if version == "3.0" else "Window"

    fresh_import(gml, version)
    baseline_path = out_dir / f"edit_{version.replace('.', '_')}_baseline.gml"
    export(baseline_path, version)

    fresh_import(gml, version)
    window = next(o for o in bpy.data.objects if o.get("cgml3_feature") == win_key)
    for v in window.data.vertices:
        v.co.z += 2.5
    for o in bpy.data.objects:
        o.select_set(False)
    window.select_set(True)
    bpy.context.view_layer.objects.active = window
    sync_res = bpy.ops.cgml3.sync_opening_to_ring()
    assert sync_res == {'FINISHED'}, sync_res

    edited_path = out_dir / f"edit_{version.replace('.', '_')}_edited.gml"
    export(edited_path, version)

    text1 = baseline_path.read_text(encoding="utf-8")
    text2 = edited_path.read_text(encoding="utf-8")
    check(version, "14_export_reflects_edit",
          text1 != text2,
          f"baseline_len={len(text1)} edited_len={len(text2)} changed={text1 != text2}")


def main():
    argv = args()
    out_dir = Path(argv[0]) if argv else Path("/tmp/cgml-out-13")
    out_dir.mkdir(parents=True, exist_ok=True)

    for version, railway, install, appear, parts in (
        ("2.0", RAILWAY_V2, INSTALL_V2, APPEAR_V2, PARTS_V2),
        ("3.0", RAILWAY_V3, INSTALL_V3, APPEAR_V3, PARTS_V3),
    ):
        print(f"\n===== schema {version} =====")
        run_railway(version, railway, out_dir)
        run_installations(version, install, out_dir)
        run_appearance(version, appear, out_dir)
        run_building_parts(version, parts, out_dir)
        run_edit_geometry(version, railway, out_dir)

    evidence_path = out_dir / "ticket13_matrix_evidence.json"
    evidence_path.write_text(json.dumps(RESULTS, indent=2, sort_keys=True), encoding="utf-8")
    print(f"\n[ticket13] evidence written to {evidence_path}")

    if FAILURES:
        print(f"\n[ticket13] {len(FAILURES)} FAILURES:")
        for f in FAILURES:
            print(f"  - {f}")
        sys.exit(1)
    print("\n[ticket13] ALL ROWS PASSED")


main()
